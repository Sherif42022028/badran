/**
 * Returns a random tip guaranteed to be different from the previous one.
 */
export function getRandomCoffeeTip(previousText?: string): string {
  if (COFFEE_TIPS.length <= 1) return COFFEE_TIPS[0] || "قهوة تستحقها كل يوم مع بن بدران.";

  let randomTip = COFFEE_TIPS[Math.floor(Math.random() * COFFEE_TIPS.length)];
  let attempts = 0;

  while (randomTip === previousText && attempts < 10) {
    randomTip = COFFEE_TIPS[Math.floor(Math.random() * COFFEE_TIPS.length)];
    attempts++;
  }

  return randomTip;
}
